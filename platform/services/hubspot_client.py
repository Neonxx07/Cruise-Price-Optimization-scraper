"""Read booking numbers out of HubSpot instead of copy-pasting them.

Neon 2026-10-05: *"i want to grab the api from hubspot from now own i do
not want to keep screenshoting and copy pasting ... i want to grab the
booking numbers."*

WHY NOT THE URL HE SENT. The endpoint from his browser was::

    app.hubspot.com/api/inbounddb-objects/v1/crm-objects/0-3/batch
        ?portalId=4757498&hs_static_app_version=2.54467&...

That is HubSpot's INTERNAL UI endpoint - the one their own CRM web app
calls. It authenticates with a browser session cookie and CSRF token, not
an API key, so outside the browser it returns 401; it is undocumented and
unversioned, and `hs_static_app_version=2.54467` in the URL is a build
number that changes whenever HubSpot ships. Building on it would recreate
exactly the fragility this project already fights on the cruise portals -
`structure_watch` caught ESPRESSO renaming a search box last week.

This uses the PUBLIC CRM v3 API instead: versioned, documented, published
rate limits, and stable across HubSpot UI deploys. `0-3` in his URL is
HubSpot's object-type id for Deals, which is why the public equivalent is
`/crm/v3/objects/deals`. The portal id is implied by the token and drops
out.

THE PROPERTY NAME IS NEVER GUESSED. A booking number lives in a CUSTOM
property whose internal name is specific to this portal - it could be
`booking_number`, `reservation_id`, or an autogenerated
`p4757498_booking`. Guessing it would silently return empty results, which
is the same class of mistake as guessing a selector. `discover_properties`
lists the real ones and ranks the likely candidates; a human confirms
before the name is used.

THE TOKEN IS NEVER IN CODE, ARGV OR A LOG. It comes from the OS keyring,
the same place the portal passwords live (see save_login.py). Nothing here
prints or returns it.
"""

from __future__ import annotations

import re
import time

import httpx

from utils.logging import get_logger

logger = get_logger(__name__)

#: Keyring service for the HubSpot private-app token. Matches the naming
#: save_login.py already uses for portal credentials.
HUBSPOT_CREDENTIAL_SERVICE = "cruiseintel-hubspot"

API_ROOT = "https://api.hubapi.com"

#: HubSpot's object-type ids. 0-3 is what Neon's own URL carried.
OBJECT_TYPES = {"contacts": "0-1", "companies": "0-2", "deals": "0-3"}

#: Words that make a property LOOK like it holds a booking reference.
#: Used only to RANK candidates for a human to confirm - never to pick one.
_CANDIDATE_WORDS = ("booking", "reservation", "confirmation", "res_", "resid",
                    "bkg", "cruise", "voyage")

#: A cruise booking reference as these portals issue them: 5-9 digits.
#: ESPRESSO is 6-7, NCL and MSC 8. Used to SANITY-CHECK what came back,
#: not to invent values.
_BOOKING_SHAPED = re.compile(r"^\d{5,9}$")


class HubSpotError(RuntimeError):
    """A HubSpot call failed in a way the caller must see."""


def get_token() -> str | None:
    """The private-app token from the OS keyring, or None.

    Never falls back to an environment variable or a file - one place for
    a secret is the whole point, and a second one is how a token ends up
    committed.
    """
    try:
        import keyring

        return keyring.get_password(HUBSPOT_CREDENTIAL_SERVICE, "token")
    except Exception as exc:  # noqa: BLE001
        logger.warning("hubspot.keyring_unavailable", error=str(exc)[:200])
        return None


class HubSpotClient:
    """Minimal, read-only HubSpot CRM v3 client.

    READ-ONLY BY CONSTRUCTION: this class issues GET and the documented
    `/search` POST, and nothing else. It cannot modify a CRM record,
    because an automation that can quietly rewrite the company's CRM is a
    much larger thing to trust than one that reads booking numbers.
    """

    def __init__(self, token: str | None = None, timeout: float = 20.0) -> None:
        self._token = token or get_token()
        if not self._token:
            raise HubSpotError(
                "No HubSpot token in the keyring. Store one under service "
                f"'{HUBSPOT_CREDENTIAL_SERVICE}', key 'token' - never in "
                "code, in a command line, or pasted into chat.")
        self._timeout = timeout

    # ── plumbing ─────────────────────────────────────────────────────

    def _headers(self) -> dict:
        return {"Authorization": f"Bearer {self._token}",
                "Content-Type": "application/json"}

    def _request(self, method: str, path: str, *, params=None, json=None,
                 attempts: int = 4):
        """One call, with backoff on 429 and 5xx.

        HubSpot rate-limits private apps per 10-second window and answers
        429 with a `Retry-After`. Honouring it is the difference between a
        pause and a temporarily blocked token.

        The token is never logged - only the status and the path.
        """
        url = f"{API_ROOT}{path}"
        delay = 1.0
        last = ""
        for attempt in range(1, attempts + 1):
            try:
                response = httpx.request(
                    method, url, headers=self._headers(), params=params,
                    json=json, timeout=self._timeout)
            except Exception as exc:  # noqa: BLE001
                last = f"transport: {str(exc)[:160]}"
                logger.warning("hubspot.transport_error", path=path,
                               attempt=attempt, error=str(exc)[:160])
                time.sleep(delay)
                delay *= 2
                continue

            if response.status_code == 200:
                return response.json()

            if response.status_code == 401:
                # Never retried: a bad token does not become good, and
                # hammering an auth endpoint is how a token gets blocked.
                raise HubSpotError(
                    "HubSpot rejected the token (401). Check the private "
                    "app still exists and has the scopes it needs.")
            if response.status_code == 403:
                raise HubSpotError(
                    "HubSpot refused the request (403) - the private app is "
                    "missing a scope for this object. Add the read scope for "
                    "it in HubSpot settings.")

            if response.status_code == 429 or response.status_code >= 500:
                wait = delay
                header = response.headers.get("Retry-After")
                if header:
                    try:
                        wait = float(header)
                    except ValueError:
                        pass
                logger.warning("hubspot.retrying", path=path,
                               status=response.status_code, attempt=attempt,
                               wait_s=wait)
                last = f"HTTP {response.status_code}"
                time.sleep(wait)
                delay *= 2
                continue

            raise HubSpotError(
                f"HubSpot returned HTTP {response.status_code} for {path}: "
                f"{response.text[:200]}")

        raise HubSpotError(f"HubSpot call to {path} failed after "
                           f"{attempts} attempts ({last})")

    # ── discovery ────────────────────────────────────────────────────

    def discover_properties(self, object_type: str = "deals") -> list[dict]:
        """Every property on an object, with likely booking fields first.

        RUN THIS BEFORE ANYTHING ELSE. The booking number is a custom
        property whose internal name belongs to this portal alone -
        guessing it returns empty results that look like "no bookings
        found", which is worse than an error.

        Returns dicts of `{name, label, type, likely}`, most likely first.
        `likely` is a RANKING HINT for a human, not a decision.
        """
        payload = self._request("GET", f"/crm/v3/properties/{object_type}")
        out = []
        for prop in payload.get("results", []):
            name = prop.get("name", "")
            label = prop.get("label", "") or ""
            haystack = f"{name} {label}".lower()
            out.append({
                "name": name,
                "label": label,
                "type": prop.get("type"),
                "likely": any(word in haystack for word in _CANDIDATE_WORDS),
            })
        out.sort(key=lambda p: (not p["likely"], p["name"]))
        logger.info("hubspot.properties_discovered",
                    object_type=object_type, total=len(out),
                    likely=sum(1 for p in out if p["likely"]))
        return out

    # ── reading ──────────────────────────────────────────────────────

    def iter_objects(self, object_type: str, properties: list[str],
                     page_size: int = 100, max_pages: int = 200):
        """Every object, one page at a time, following HubSpot's cursor.

        Bounded by `max_pages` so a misconfigured call cannot walk a
        100,000-record portal in a loop nobody is watching.
        """
        after = None
        for page in range(max_pages):
            params = {"limit": page_size, "properties": properties}
            if after:
                params["after"] = after
            payload = self._request("GET", f"/crm/v3/objects/{object_type}",
                                    params=params)
            results = payload.get("results", [])
            yield from results

            after = (payload.get("paging", {}).get("next", {}) or {}).get("after")
            if not after:
                return
            if page == max_pages - 1:
                logger.warning("hubspot.page_limit_reached",
                               object_type=object_type, max_pages=max_pages)

    def booking_numbers(self, property_name: str,
                        object_type: str = "deals",
                        extra_properties: list[str] | None = None) -> dict:
        """Booking numbers from `property_name`, de-duplicated.

        `property_name` is REQUIRED and has no default on purpose. There
        is no safe guess, and a wrong one returns an empty list that reads
        as "no bookings".

        Returns::

            {"booking_ids": [...],      # unique, in the order found
             "records": [...],          # id + properties, for matching back
             "skipped_blank": int,      # records with the property empty
             "skipped_odd": int}        # values that are not booking-shaped

        The two skip counts matter: a property that yields 400 blanks is
        the WRONG property, and this says so instead of returning [].
        """
        wanted = [property_name] + list(extra_properties or [])
        booking_ids: list[str] = []
        seen: set[str] = set()
        records: list[dict] = []
        blank = odd = 0

        for obj in self.iter_objects(object_type, wanted):
            props = obj.get("properties") or {}
            raw = props.get(property_name)
            value = str(raw).strip() if raw is not None else ""
            if not value:
                blank += 1
                continue
            if not _BOOKING_SHAPED.match(value):
                # Kept in `records` so a human can look - not silently
                # dropped, and not silently accepted either.
                odd += 1
                records.append({"id": obj.get("id"), "value": value,
                                "properties": props, "booking_shaped": False})
                continue
            if value not in seen:
                seen.add(value)
                booking_ids.append(value)
            records.append({"id": obj.get("id"), "value": value,
                            "properties": props, "booking_shaped": True})

        logger.info("hubspot.booking_numbers",
                    object_type=object_type, property=property_name,
                    found=len(booking_ids), blank=blank, odd=odd)
        return {"booking_ids": booking_ids, "records": records,
                "skipped_blank": blank, "skipped_odd": odd}
